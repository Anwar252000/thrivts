import { num, rs } from '@shared/format'

export interface PrintableInvoice {
  number?: string
  lotSerial: string
  supplierName: string
  final: boolean
  date: string
  lines: { itemName: string; pieces: number; buyPrice: number; accepted?: boolean }[]
  rejections: { itemName: string; rejected: number; reason: string | null; accepted: number }[]
}

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!)

/** The legacy printable vendor invoice: opens a clean document and the print dialog, where it can
 *  be saved as a PDF. Every value is escaped before it is written into the page. */
export function printInvoice(inv: PrintableInvoice) {
  const items = inv.lines.filter((l) => !l.accepted && l.pieces > 0)
  const accepted = inv.lines.filter((l) => l.accepted && l.pieces > 0)
  const itemsT = items.reduce((a, l) => a + l.pieces * l.buyPrice, 0)
  const accT = accepted.reduce((a, l) => a + l.pieces * l.buyPrice, 0)
  const row = (l: PrintableInvoice['lines'][number]) =>
    `<tr><td>${esc(l.itemName)}${l.accepted ? ' <span class="mut">(accepted rejections)</span>' : ''}</td><td class="r">${num(l.pieces)}</td><td class="r">${rs(l.buyPrice)}</td><td class="r">${rs(l.pieces * l.buyPrice)}</td></tr>`
  const rejRows = inv.rejections.filter((r) => r.rejected > 0)
    .map((r) => `<tr><td>${esc(r.itemName)}</td><td class="r">${num(r.rejected)}</td><td>${esc(r.reason || '—')}</td><td class="r">${num(r.accepted)}</td><td class="r">${num(r.rejected - r.accepted)}</td></tr>`).join('')

  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Invoice ${esc(inv.lotSerial)} — ${esc(inv.supplierName)}</title>
<style>
*{box-sizing:border-box} body{font-family:-apple-system,Segoe UI,Arial,sans-serif;color:#111;max-width:760px;margin:0 auto;padding:32px}
.hd{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #111;padding-bottom:14px;margin-bottom:18px}
.co{font-size:24px;font-weight:800} .mut{color:#777;font-size:12px}
h2{font-size:15px;margin:22px 0 6px} table{width:100%;border-collapse:collapse;font-size:13px}
th,td{text-align:left;padding:8px 6px;border-bottom:1px solid #e3e3e3} th{background:#f5f5f5;font-size:11px;text-transform:uppercase;color:#555}
td.r,th.r{text-align:right} .tot{display:flex;justify-content:flex-end;margin-top:14px}
.tot table{width:auto;min-width:280px} .tot td{border:none;padding:4px 6px} .grand td{font-size:17px;font-weight:800;border-top:2px solid #111;padding-top:8px}
.foot{margin-top:28px;font-size:11px;color:#888;border-top:1px solid #e3e3e3;padding-top:10px}
@media print{body{padding:0}}
</style></head><body>
<div class="hd"><div><div class="co">Vintage Hub</div><div class="mut">Wholesale used clothing · Karachi</div></div>
<div style="text-align:right"><div style="font-size:18px;font-weight:800">VENDOR INVOICE</div><div class="mut">${inv.number ? esc(inv.number) + ' · ' : ''}Lot ${esc(inv.lotSerial)} · ${esc(inv.date)}</div></div></div>
<div style="display:flex;justify-content:space-between;margin-bottom:10px">
<div><div class="mut">Vendor</div><div style="font-weight:700;font-size:15px">${esc(inv.supplierName)}</div></div>
<div style="text-align:right"><div class="mut">Status</div><div style="font-weight:700">${inv.final ? 'Finalized (graded)' : 'Non-graded'}</div></div></div>
<h2>Accepted stock</h2>
<table><thead><tr><th>Item</th><th class="r">Pcs</th><th class="r">Rs/pc</th><th class="r">Amount</th></tr></thead>
<tbody>${items.map(row).join('') || '<tr><td colspan=4 class=mut>—</td></tr>'}${accepted.map(row).join('')}</tbody></table>
${rejRows ? `<h2>Rejections</h2><table><thead><tr><th>Item</th><th class="r">Rejected</th><th>Reason</th><th class="r">Accepted</th><th class="r">Returned</th></tr></thead><tbody>${rejRows}</tbody></table>` : ''}
<div class="tot"><table>
<tr><td>Items</td><td class="r">${rs(itemsT)}</td></tr>
${accT ? `<tr><td>Accepted rejections</td><td class="r">${rs(accT)}</td></tr>` : ''}
<tr class="grand"><td>Total</td><td class="r">${rs(itemsT + accT)}</td></tr>
</table></div>
<div class="foot">Generated by Vintage Hub ops · ${esc(inv.date)}. This invoice covers lot ${esc(inv.lotSerial)} only.</div>
</body></html>`

  const w = window.open('', '_blank')
  if (!w) {
    alert('Allow pop-ups to open the invoice PDF.')
    return
  }
  w.document.write(html)
  w.document.close()
  setTimeout(() => w.print(), 400)
}
